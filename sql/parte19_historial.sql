-- - Todo lo que se agrega, cambia o borra desde la web queda anotado: quién,
--   cuándo y qué cambió (el valor de antes y el de después). Lo de QGIS y QField
--   no se anota.
-- - El administrador ve el historial y puede deshacer un cambio.
-- - Cambiar la forma de un triángulo o padrón ya no pide aprobación (queda en
--   el historial). Lo único que sigue pidiendo aprobación es borrar.
-- - El historial se guarda 30 días.
