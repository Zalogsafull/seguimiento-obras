BEGIN;

CREATE TABLE IF NOT EXISTS public.historial (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tx             bigint NOT NULL,
  cuando         timestamptz NOT NULL DEFAULT now(),
  usuario_id     text,
  usuario_nombre text,
  tabla          text NOT NULL,
  tipo           text NOT NULL,
  objeto_id      bigint,
  codigo         text,
  detalle        text,
  padre_tipo     text,
  padre_id       bigint,
  op             text NOT NULL CHECK (op IN ('INSERT', 'UPDATE', 'DELETE')),
  antes          jsonb,
  despues        jsonb,
  geom_antes     geometry,
  geom_despues   geometry,
  deshace_tx     bigint,
  deshecho       boolean NOT NULL DEFAULT false,
  deshecho_por   text,
  deshecho_cuando timestamptz
);
CREATE INDEX IF NOT EXISTS historial_cuando_idx ON public.historial (cuando);
CREATE INDEX IF NOT EXISTS historial_tx_idx ON public.historial (tx);
REVOKE ALL ON public.historial FROM PUBLIC;
ALTER TABLE public.historial ENABLE ROW LEVEL SECURITY;

-- Anota cada fila agregada, cambiada o borrada desde la web (solo con usuario de la web)
CREATE OR REPLACE FUNCTION public.anotar_historial() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $fn$
DECLARE
  v_uid    text;
  v_antes  jsonb;
  v_desp   jsonb;
  v_fila   jsonb;
  v_ga     geometry;
  v_gd     geometry;
  v_geom   boolean;
  v_tipo   text;
  v_codigo text;
  v_det    text;
  v_ptipo  text;
  v_pid    bigint;
  v_nombre text;
BEGIN
  BEGIN
    v_uid := nullif(trim(auth.user_id()), '');
  EXCEPTION WHEN others THEN
    v_uid := NULL;
  END;
  IF v_uid IS NULL THEN
    RETURN NULL;
  END IF;
  v_geom := TG_TABLE_NAME NOT IN ('hitos', 'cuaderno');
  IF TG_OP <> 'INSERT' THEN
    v_antes := to_jsonb(OLD) - 'geom';
    IF v_geom THEN v_ga := OLD.geom; END IF;
  END IF;
  IF TG_OP <> 'DELETE' THEN
    v_desp := to_jsonb(NEW) - 'geom';
    IF v_geom THEN v_gd := NEW.geom; END IF;
  END IF;
  IF TG_OP = 'UPDATE' AND (v_antes - 'modificado') = (v_desp - 'modificado')
     AND v_ga::text IS NOT DISTINCT FROM v_gd::text THEN
    RETURN NULL;
  END IF;
  v_fila := coalesce(v_desp, v_antes);
  v_tipo := CASE TG_TABLE_NAME WHEN 'Estructuras OICI Obra' THEN 'estructura' WHEN 'Obras' THEN 'obra'
                               WHEN 'Relevamiento' THEN 'relevamiento' WHEN 'Amojonamiento' THEN 'amojonamiento'
                               WHEN 'Triangulos' THEN 'triangulo' WHEN 'Padrones' THEN 'padron'
                               WHEN 'hitos' THEN 'hito' WHEN 'cuaderno' THEN 'cuaderno' ELSE TG_TABLE_NAME END;
  IF v_tipo IN ('hito', 'cuaderno') THEN
    IF v_fila->>'estructura_id' IS NOT NULL THEN
      v_ptipo := 'estructura';
      v_pid := (v_fila->>'estructura_id')::bigint;
      SELECT to_jsonb(e)->>'CÓDIGO' INTO v_codigo FROM public."Estructuras OICI Obra" e WHERE e.fid = v_pid;
    ELSE
      v_ptipo := 'obra';
      v_pid := (v_fila->>'obra_id')::bigint;
      SELECT to_jsonb(o)->>'CÓDIGO' INTO v_codigo FROM public."Obras" o WHERE o.fid = v_pid;
    END IF;
    v_det := CASE WHEN v_tipo = 'hito' THEN v_fila->>'nombre' ELSE left(v_fila->>'texto', 80) END;
  ELSE
    v_codigo := coalesce(v_fila->>'CÓDIGO', CASE WHEN v_fila ? 'PADRON' THEN 'Padrón ' || coalesce(v_fila->>'PADRON', 'sin número') END);
  END IF;
  SELECT nombre INTO v_nombre FROM public.usuarios_web WHERE user_id = v_uid;
  INSERT INTO public.historial (tx, usuario_id, usuario_nombre, tabla, tipo, objeto_id, codigo, detalle, padre_tipo, padre_id,
                                op, antes, despues, geom_antes, geom_despues, deshace_tx)
  VALUES (txid_current(), v_uid, v_nombre, TG_TABLE_NAME, v_tipo, coalesce((v_fila->>'fid')::bigint, (v_fila->>'id')::bigint),
          v_codigo, v_det, v_ptipo, v_pid, TG_OP, v_antes, v_desp, v_ga, v_gd,
          nullif(current_setting('app.deshacer', true), '')::bigint);
  RETURN NULL;
END $fn$;
REVOKE ALL ON FUNCTION public.anotar_historial() FROM PUBLIC;

-- El historial dura 30 días
CREATE OR REPLACE FUNCTION public.limpiar_historial() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $fn$
BEGIN
  DELETE FROM public.historial WHERE cuando < now() - interval '30 days';
  RETURN NULL;
END $fn$;
REVOKE ALL ON FUNCTION public.limpiar_historial() FROM PUBLIC;
DROP TRIGGER IF EXISTS limpiar_historial ON public.historial;
CREATE TRIGGER limpiar_historial AFTER INSERT ON public.historial
  FOR EACH STATEMENT EXECUTE FUNCTION public.limpiar_historial();

-- El disparador en cada capa (las que existan)
DO $do$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['Estructuras OICI Obra', 'Obras', 'Relevamiento', 'Amojonamiento', 'Triangulos', 'Padrones', 'hitos', 'cuaderno'] LOOP
    IF to_regclass(format('public.%I', t)) IS NOT NULL THEN
      EXECUTE format('DROP TRIGGER IF EXISTS anotar_historial ON public.%I', t);
      EXECUTE format('CREATE TRIGGER anotar_historial AFTER INSERT OR UPDATE OR DELETE ON public.%I
                      FOR EACH ROW EXECUTE FUNCTION public.anotar_historial()', t);
    END IF;
  END LOOP;
END $do$;

-- El historial para la web (solo administradores): lo último primero
CREATE OR REPLACE FUNCTION public.historial_cambios(p_dias integer DEFAULT 30) RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $fn$
BEGIN
  IF NOT public.es_admin() THEN
    RAISE EXCEPTION 'Solo un administrador puede ver el historial';
  END IF;
  RETURN (SELECT coalesce(jsonb_agg(jsonb_build_object(
      'id', h.id, 'tx', h.tx, 'cuando', h.cuando, 'usuario_id', h.usuario_id, 'usuario', h.usuario_nombre,
      'tipo', h.tipo, 'objeto_id', h.objeto_id, 'codigo', h.codigo, 'detalle', h.detalle,
      'padre_tipo', h.padre_tipo, 'padre_id', h.padre_id, 'op', h.op, 'antes', h.antes, 'despues', h.despues,
      'geom_cambio', h.op = 'UPDATE' AND h.geom_antes::text IS DISTINCT FROM h.geom_despues::text,
      'deshace_tx', h.deshace_tx, 'deshecho', h.deshecho, 'deshecho_por', u.nombre, 'deshecho_cuando', h.deshecho_cuando)
      ORDER BY h.id DESC), '[]'::jsonb)
    FROM (SELECT * FROM public.historial WHERE cuando > now() - make_interval(days => p_dias) ORDER BY id DESC LIMIT 1500) h
    LEFT JOIN public.usuarios_web u ON u.user_id = h.deshecho_por);
END $fn$;

-- Clave y columnas de cada tabla (uso interno)
CREATE OR REPLACE FUNCTION public.columnas_de(p_tabla text, p_sin_clave boolean) RETURNS text
LANGUAGE sql STABLE SET search_path = public AS $fn$
  SELECT string_agg(quote_ident(c.column_name), ', ' ORDER BY c.ordinal_position)
  FROM information_schema.columns c
  WHERE c.table_schema = 'public' AND c.table_name = p_tabla AND c.column_name <> 'geom' AND c.is_generated = 'NEVER'
    AND NOT (p_sin_clave AND c.column_name = CASE WHEN p_tabla IN ('hitos', 'cuaderno') THEN 'id' ELSE 'fid' END)
$fn$;

-- Deshacer un cambio (todo lo que se hizo junto en ese momento)
CREATE OR REPLACE FUNCTION public.deshacer_cambio(p_tx bigint, p_forzar boolean DEFAULT false) RETURNS text
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $fn$
DECLARE
  h       public.historial;
  v_clave text;
  v_ahora jsonb;
  v_gahora geometry;
  v_geom  boolean;
  v_cols  text;
  v_cambio boolean := false;
  v_n     integer := 0;
BEGIN
  IF NOT public.es_admin() THEN
    RAISE EXCEPTION 'Solo un administrador puede deshacer cambios';
  END IF;
  FOR h IN SELECT * FROM public.historial WHERE tx = p_tx AND NOT deshecho ORDER BY id LOOP
    v_n := v_n + 1;
    v_clave := CASE WHEN h.tabla IN ('hitos', 'cuaderno') THEN 'id' ELSE 'fid' END;
    v_geom := h.tabla NOT IN ('hitos', 'cuaderno');
    EXECUTE format('SELECT to_jsonb(t) - ''geom'' FROM public.%I t WHERE %I = $1', h.tabla, v_clave) INTO v_ahora USING h.objeto_id;
    IF h.op = 'DELETE' AND v_ahora IS NOT NULL THEN
      v_cambio := true;
    ELSIF h.op IN ('INSERT', 'UPDATE') AND v_ahora IS NOT NULL
          AND (v_ahora - 'modificado') IS DISTINCT FROM (h.despues - 'modificado') THEN
      v_cambio := true;
    ELSIF h.op = 'UPDATE' AND v_ahora IS NULL THEN
      v_cambio := true;
    END IF;
    IF v_geom AND v_ahora IS NOT NULL AND h.op <> 'DELETE' THEN
      EXECUTE format('SELECT t.geom FROM public.%I t WHERE %I = $1', h.tabla, v_clave) INTO v_gahora USING h.objeto_id;
      IF v_gahora::text IS DISTINCT FROM h.geom_despues::text THEN
        v_cambio := true;
      END IF;
    END IF;
  END LOOP;
  IF v_n = 0 THEN
    RETURN 'NADA';
  END IF;
  IF v_cambio AND NOT p_forzar THEN
    RETURN 'CAMBIADO_DESPUES';
  END IF;

  PERFORM set_config('app.deshacer', p_tx::text, true);
  FOR h IN SELECT * FROM public.historial WHERE tx = p_tx AND NOT deshecho AND op = 'DELETE'
           ORDER BY (tabla IN ('hitos', 'cuaderno')), id LOOP
    v_clave := CASE WHEN h.tabla IN ('hitos', 'cuaderno') THEN 'id' ELSE 'fid' END;
    v_geom := h.tabla NOT IN ('hitos', 'cuaderno');
    EXECUTE format('SELECT to_jsonb(t) FROM public.%I t WHERE %I = $1', h.tabla, v_clave) INTO v_ahora USING h.objeto_id;
    IF v_ahora IS NULL THEN
      v_cols := public.columnas_de(h.tabla, false);
      IF v_geom THEN
        EXECUTE format('INSERT INTO public.%I (%s, geom) OVERRIDING SYSTEM VALUE SELECT %s, $2 FROM jsonb_populate_record(NULL::public.%I, $1)',
                       h.tabla, v_cols, v_cols, h.tabla) USING h.antes, h.geom_antes;
        IF h.tabla IN ('Estructuras OICI Obra', 'Obras') THEN
          EXECUTE format('DELETE FROM public.hitos WHERE %I = $1 AND id NOT IN (SELECT objeto_id FROM public.historial WHERE tx = $2 AND tabla = ''hitos'' AND op = ''DELETE'')',
                         CASE WHEN h.tabla = 'Obras' THEN 'obra_id' ELSE 'estructura_id' END) USING h.objeto_id, p_tx;
        END IF;
      ELSE
        EXECUTE format('INSERT INTO public.%I (%s) OVERRIDING SYSTEM VALUE SELECT %s FROM jsonb_populate_record(NULL::public.%I, $1)',
                       h.tabla, v_cols, v_cols, h.tabla) USING h.antes;
      END IF;
    END IF;
  END LOOP;
  FOR h IN SELECT * FROM public.historial WHERE tx = p_tx AND NOT deshecho AND op = 'UPDATE' ORDER BY id DESC LOOP
    v_clave := CASE WHEN h.tabla IN ('hitos', 'cuaderno') THEN 'id' ELSE 'fid' END;
    v_cols := public.columnas_de(h.tabla, true);
    IF h.tabla NOT IN ('hitos', 'cuaderno') THEN
      EXECUTE format('UPDATE public.%I t SET (%s) = (SELECT %s FROM jsonb_populate_record(NULL::public.%I, $1)), geom = $2 WHERE t.%I = $3',
                     h.tabla, v_cols, v_cols, h.tabla, v_clave) USING h.antes, h.geom_antes, h.objeto_id;
    ELSE
      EXECUTE format('UPDATE public.%I t SET (%s) = (SELECT %s FROM jsonb_populate_record(NULL::public.%I, $1)) WHERE t.%I = $2',
                     h.tabla, v_cols, v_cols, h.tabla, v_clave) USING h.antes, h.objeto_id;
    END IF;
  END LOOP;
  FOR h IN SELECT * FROM public.historial WHERE tx = p_tx AND NOT deshecho AND op = 'INSERT' ORDER BY id DESC LOOP
    v_clave := CASE WHEN h.tabla IN ('hitos', 'cuaderno') THEN 'id' ELSE 'fid' END;
    EXECUTE format('DELETE FROM public.%I WHERE %I = $1', h.tabla, v_clave) USING h.objeto_id;
  END LOOP;
  UPDATE public.historial SET deshecho = true, deshecho_por = auth.user_id(), deshecho_cuando = now()
  WHERE tx = p_tx AND NOT deshecho;
  RETURN 'DESHECHO';
END $fn$;

-- Cambiar la forma de un polígono ya no pide aprobación: se aplica y queda en el historial
CREATE OR REPLACE FUNCTION public.editar_poligono(p_tipo text, p_id integer, p_vertices jsonb, p_datos jsonb)
RETURNS text
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $fn$
DECLARE
  v_tabla  text;
  v_fila   jsonb;
  v_codigo text;
  v_nombre text;
  v_resp   jsonb;
BEGIN
  IF coalesce(public.rol_web(), '') <> 'EDITOR' THEN
    RAISE EXCEPTION 'Solo un usuario con permiso de editor puede cambiar polígonos';
  END IF;
  v_tabla := CASE p_tipo WHEN 'triangulo' THEN 'Triangulos' WHEN 'padron' THEN 'Padrones' END;
  IF v_tabla IS NULL THEN
    RAISE EXCEPTION 'Capa desconocida: %', p_tipo;
  END IF;
  EXECUTE format('SELECT to_jsonb(t) - ''geom'' FROM public.%I t WHERE fid = $1', v_tabla) INTO v_fila USING p_id;
  IF v_fila IS NULL THEN
    RAISE EXCEPTION 'Ya no existe: puede que otra persona lo haya borrado';
  END IF;
  v_codigo := nullif(coalesce(v_fila->>'CÓDIGO',
                              CASE WHEN v_fila ? 'PADRON' THEN 'Padrón ' || coalesce(v_fila->>'PADRON', 'sin número') END, ''), '');
  SELECT nombre INTO v_nombre FROM public.usuarios_web WHERE user_id = auth.user_id();
  v_resp := public.aplicar_forma(p_tipo, p_id, p_vertices, p_datos);
  INSERT INTO public.solicitudes_forma (tipo, objeto_id, codigo, vertices, datos, pedido_por, pedido_nombre,
                                        estado, resuelto_por, resuelto, respaldo)
  VALUES (p_tipo, p_id, v_codigo, p_vertices, p_datos, auth.user_id(), v_nombre, 'APLICADA', auth.user_id(), now(), v_resp);
  RETURN 'APLICADO';
END $fn$;

REVOKE ALL ON FUNCTION public.historial_cambios(integer), public.deshacer_cambio(bigint, boolean),
  public.columnas_de(text, boolean) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.historial_cambios(integer), public.deshacer_cambio(bigint, boolean) TO authenticated;

COMMIT;

