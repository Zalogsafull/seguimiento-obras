BEGIN;

-- 1. Lectura desde la web (solo usuarios habilitados)
GRANT SELECT ON public."Amojonamiento", public."Triangulos", public."Padrones" TO authenticated;
ALTER TABLE public."Amojonamiento" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."Triangulos" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."Padrones" ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS web_ver ON public."Amojonamiento";
DROP POLICY IF EXISTS web_ver ON public."Triangulos";
DROP POLICY IF EXISTS web_ver ON public."Padrones";
CREATE POLICY web_ver ON public."Amojonamiento" FOR SELECT TO authenticated USING (public.rol_web() IS NOT NULL);
CREATE POLICY web_ver ON public."Triangulos" FOR SELECT TO authenticated USING (public.rol_web() IS NOT NULL);
CREATE POLICY web_ver ON public."Padrones" FOR SELECT TO authenticated USING (public.rol_web() IS NOT NULL);

-- 2. Si fid no se numera solo (pasó al importar las capas), se le pone numeración automática.
DO $do$
DECLARE t text; v_max bigint;
BEGIN
  FOREACH t IN ARRAY ARRAY['Amojonamiento', 'Triangulos', 'Padrones'] LOOP
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = t AND column_name = 'fid'
                 AND column_default IS NULL AND is_identity = 'NO') THEN
      EXECUTE format('ALTER TABLE public.%I ALTER COLUMN fid ADD GENERATED BY DEFAULT AS IDENTITY', t);
      EXECUTE format('SELECT coalesce(max(fid), 0) + 1 FROM public.%I', t) INTO v_max;
      PERFORM setval(pg_get_serial_sequence(format('public.%I', t), 'fid'), v_max, false);
    END IF;
  END LOOP;
END $do$;

-- 3. Vistas para la web, en WGS 84. Se arman con las columnas que existan de verdad
--    (sin importar mayúsculas ni tildes); si falta alguna, queda vacía.
CREATE OR REPLACE FUNCTION pg_temp.columna(p_tabla text, p_nombre text, p_alias text) RETURNS text
LANGUAGE sql AS $fn$
  SELECT coalesce(
    (SELECT format('t.%I::text AS %I', c.column_name, p_alias) FROM information_schema.columns c
     WHERE c.table_schema = 'public' AND c.table_name = p_tabla
       AND translate(upper(c.column_name), 'ÁÉÍÓÚ', 'AEIOU') = translate(upper(p_nombre), 'ÁÉÍÓÚ', 'AEIOU')
     LIMIT 1),
    format('NULL::text AS %I', p_alias))
$fn$;

DO $do$
BEGIN
  EXECUTE 'DROP VIEW IF EXISTS public.v_amojonamiento';
  EXECUTE format($v$
    CREATE VIEW public.v_amojonamiento WITH (security_invoker = true) AS
    SELECT t.fid AS id, %s, %s,
      ST_Y(ST_Transform(ST_Force2D(t.geom), 4326)) AS lat,
      ST_X(ST_Transform(ST_Force2D(t.geom), 4326)) AS lon
    FROM public."Amojonamiento" t WHERE t.geom IS NOT NULL$v$,
    pg_temp.columna('Amojonamiento', 'CÓDIGO', 'codigo'), pg_temp.columna('Amojonamiento', 'DESCRIPCION', 'descripcion'));

  EXECUTE 'DROP VIEW IF EXISTS public.v_triangulos';
  EXECUTE format($v$
    CREATE VIEW public.v_triangulos WITH (security_invoker = true) AS
    SELECT t.fid AS id, %s,
      round(ST_Area(t.geom)::numeric, 1) AS area_m2,
      ST_AsGeoJSON(ST_Transform(ST_Force2D(t.geom), 4326), 7) AS geojson
    FROM public."Triangulos" t WHERE t.geom IS NOT NULL$v$,
    pg_temp.columna('Triangulos', 'CÓDIGO', 'codigo'));

  EXECUTE 'DROP VIEW IF EXISTS public.v_padrones';
  EXECUTE format($v$
    CREATE VIEW public.v_padrones WITH (security_invoker = true) AS
    SELECT t.fid AS id, %s,
      round(ST_Area(t.geom)::numeric, 1) AS area_m2,
      ST_AsGeoJSON(ST_Transform(ST_Force2D(t.geom), 4326), 7) AS geojson
    FROM public."Padrones" t WHERE t.geom IS NOT NULL$v$,
    pg_temp.columna('Padrones', 'PADRON', 'padron'));
END $do$;
GRANT SELECT ON public.v_amojonamiento, public.v_triangulos, public.v_padrones TO authenticated;

-- 4. Agregar puntos: la misma función de siempre, ahora también para Amojonamiento.
CREATE OR REPLACE FUNCTION public.crear_punto(p_capa text, p_lat double precision, p_lon double precision, p_datos jsonb)
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $fn$
DECLARE
  v_tabla  text;
  v_geom   geometry;
  v_wgs    geometry;
  v_lat    double precision;
  v_lon    double precision;
  v_z      double precision;
  v_dim    integer;
  v_tipo   text;
  v_datos  jsonb;
  v_cols   text;
  v_nuevo  integer;
BEGIN
  v_datos := coalesce(p_datos, '{}'::jsonb);
  IF coalesce(public.rol_web(), '') <> 'EDITOR' THEN
    RAISE EXCEPTION 'Solo un usuario con permiso de editor puede agregar puntos';
  END IF;
  v_tabla := CASE p_capa WHEN 'estructura' THEN 'Estructuras OICI Obra' WHEN 'obra' THEN 'Obras'
                         WHEN 'relevamiento' THEN 'Relevamiento' WHEN 'amojonamiento' THEN 'Amojonamiento' END;
  IF v_tabla IS NULL THEN
    RAISE EXCEPTION 'Capa desconocida: %', p_capa;
  END IF;
  IF p_lat IS NULL OR p_lon IS NULL OR p_lat NOT BETWEEN -36 AND -29 OR p_lon NOT BETWEEN -59.5 AND -52 THEN
    RAISE EXCEPTION 'Las coordenadas (%, %) quedan fuera de Uruguay. Revisá que la latitud vaya primero.', p_lat, p_lon;
  END IF;
  IF p_capa IN ('estructura', 'obra') AND nullif(trim(v_datos->>'CÓDIGO'), '') IS NULL THEN
    RAISE EXCEPTION 'Falta el código';
  END IF;

  BEGIN
    v_z := nullif(replace(trim(v_datos->>'Z'), ',', '.'), '')::double precision;
  EXCEPTION WHEN others THEN
    RAISE EXCEPTION 'La Z tiene que ser un número en metros (ej. 34.5)';
  END;

  SELECT coord_dimension, upper(type) INTO v_dim, v_tipo
  FROM geometry_columns WHERE f_table_schema = 'public' AND f_table_name = v_tabla AND f_geometry_column = 'geom';

  v_geom := ST_Transform(ST_SetSRID(ST_MakePoint(p_lon, p_lat), 4326), 31981);
  IF coalesce(v_dim, 2) >= 3 OR (v_tipo LIKE '%Z' OR p_capa = 'estructura') THEN
    v_geom := ST_SetSRID(ST_MakePoint(ST_X(v_geom), ST_Y(v_geom), coalesce(v_z, 0)), 31981);
  END IF;
  IF v_tipo LIKE 'MULTI%' THEN
    v_geom := ST_Multi(v_geom);
  END IF;

  v_wgs := ST_Transform(ST_Centroid(ST_Force2D(v_geom)), 4326);
  v_lat := ST_Y(v_wgs);
  v_lon := ST_X(v_wgs);
  IF p_capa = 'amojonamiento' THEN
    v_datos := v_datos || jsonb_build_object('X', ST_X(ST_Centroid(v_geom)), 'Y', ST_Y(ST_Centroid(v_geom)));
  ELSIF p_capa = 'relevamiento' THEN
    v_datos := v_datos || jsonb_build_object('LAT', v_lat, 'LONG', v_lon,
      'MAPS', 'https://www.google.com/maps/search/?api=1&query=' || v_lat::text || ',' || v_lon::text);
    IF v_z IS NOT NULL THEN
      v_datos := v_datos || jsonb_build_object('Z', v_z);
    ELSE
      v_datos := v_datos - 'Z';
    END IF;
  ELSE
    v_datos := v_datos || jsonb_build_object('LAT', v_lat, 'LONG', v_lon,
      'Maps', 'https://www.google.com/maps/dir/?api=1&destination=' || v_lat::text || '%2C' || v_lon::text || '&travelmode=driving',
      'WAZE', 'https://waze.com/ul?ll=' || v_lat::text || ',' || v_lon::text || '&navigate=yes',
      'Waze', 'https://waze.com/ul?ll=' || v_lat::text || ',' || v_lon::text || '&navigate=yes');
  END IF;

  SELECT string_agg(quote_ident(k), ', ') INTO v_cols
  FROM jsonb_object_keys(v_datos) AS k
  WHERE k NOT IN ('fid', 'geom', 'ETAPA')
    AND EXISTS (SELECT 1 FROM information_schema.columns c
                WHERE c.table_schema = 'public' AND c.table_name = v_tabla AND c.column_name = k);

  IF v_cols IS NULL THEN
    EXECUTE format('INSERT INTO public.%I (geom) VALUES ($1) RETURNING fid', v_tabla) USING v_geom INTO v_nuevo;
  ELSE
    EXECUTE format('INSERT INTO public.%I (%s, geom) SELECT %s, $2 FROM jsonb_populate_record(NULL::public.%I, $1) RETURNING fid',
                   v_tabla, v_cols, v_cols, v_tabla)
      USING v_datos, v_geom INTO v_nuevo;
  END IF;
  RETURN v_nuevo;
END $fn$;

-- 5. Agregar polígonos (Triángulos y Padrones): vértices en WGS 84 [[lon, lat], ...].
--    El polígono se cierra solo; si los vértices se cruzan, se corrige la forma.
CREATE OR REPLACE FUNCTION public.crear_poligono(p_capa text, p_vertices jsonb, p_datos jsonb)
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $fn$
DECLARE
  v_tabla  text;
  v_pts    geometry[];
  v_geom   geometry;
  v_dim    integer;
  v_tipo   text;
  v_datos  jsonb;
  v_cols   text;
  v_nuevo  integer;
  v_p      jsonb;
  v_lon    double precision;
  v_lat    double precision;
BEGIN
  v_datos := coalesce(p_datos, '{}'::jsonb);
  IF coalesce(public.rol_web(), '') <> 'EDITOR' THEN
    RAISE EXCEPTION 'Solo un usuario con permiso de editor puede agregar polígonos';
  END IF;
  v_tabla := CASE p_capa WHEN 'triangulo' THEN 'Triangulos' WHEN 'padron' THEN 'Padrones' END;
  IF v_tabla IS NULL THEN
    RAISE EXCEPTION 'Capa desconocida: %', p_capa;
  END IF;
  IF jsonb_typeof(p_vertices) <> 'array' OR jsonb_array_length(p_vertices) < 3 THEN
    RAISE EXCEPTION 'Un polígono necesita al menos 3 vértices';
  END IF;
  FOR v_p IN SELECT * FROM jsonb_array_elements(p_vertices) LOOP
    v_lon := (v_p->>0)::double precision;
    v_lat := (v_p->>1)::double precision;
    IF v_lat IS NULL OR v_lon IS NULL OR v_lat NOT BETWEEN -36 AND -29 OR v_lon NOT BETWEEN -59.5 AND -52 THEN
      RAISE EXCEPTION 'El vértice (%, %) queda fuera de Uruguay', v_lat, v_lon;
    END IF;
    v_pts := v_pts || ST_Transform(ST_SetSRID(ST_MakePoint(v_lon, v_lat), 4326), 31981);
  END LOOP;
  IF NOT ST_Equals(v_pts[1], v_pts[array_length(v_pts, 1)]) THEN
    v_pts := v_pts || v_pts[1];
  END IF;
  v_geom := ST_MakePolygon(ST_MakeLine(v_pts));
  IF NOT ST_IsValid(v_geom) THEN
    v_geom := ST_CollectionExtract(ST_MakeValid(v_geom), 3);
    IF ST_NumGeometries(v_geom) = 1 THEN
      v_geom := ST_GeometryN(v_geom, 1);
    END IF;
  END IF;
  IF ST_IsEmpty(v_geom) OR ST_Area(v_geom) < 1 THEN
    RAISE EXCEPTION 'Los vértices no forman un polígono (quedan en línea o repetidos)';
  END IF;

  SELECT coord_dimension, upper(type) INTO v_dim, v_tipo
  FROM geometry_columns WHERE f_table_schema = 'public' AND f_table_name = v_tabla AND f_geometry_column = 'geom';
  IF v_tipo LIKE 'MULTI%' THEN
    v_geom := ST_Multi(v_geom);
  ELSIF GeometryType(v_geom) = 'MULTIPOLYGON' THEN
    RAISE EXCEPTION 'Los vértices se cruzan y forman más de un polígono: revisá el orden';
  END IF;
  IF coalesce(v_dim, 2) >= 3 THEN
    v_geom := ST_Force3D(v_geom);
  END IF;
  v_geom := ST_SetSRID(v_geom, 31981);

  SELECT string_agg(quote_ident(k), ', ') INTO v_cols
  FROM jsonb_object_keys(v_datos) AS k
  WHERE k NOT IN ('fid', 'geom')
    AND EXISTS (SELECT 1 FROM information_schema.columns c
                WHERE c.table_schema = 'public' AND c.table_name = v_tabla AND c.column_name = k);

  BEGIN
    IF v_cols IS NULL THEN
      EXECUTE format('INSERT INTO public.%I (geom) VALUES ($1) RETURNING fid', v_tabla) USING v_geom INTO v_nuevo;
    ELSE
      EXECUTE format('INSERT INTO public.%I (%s, geom) SELECT %s, $2 FROM jsonb_populate_record(NULL::public.%I, $1) RETURNING fid',
                     v_tabla, v_cols, v_cols, v_tabla)
        USING v_datos, v_geom INTO v_nuevo;
    END IF;
  EXCEPTION WHEN invalid_text_representation OR numeric_value_out_of_range THEN
    RAISE EXCEPTION 'El número de padrón tiene que ser un número entero';
  END;
  RETURN v_nuevo;
END $fn$;

REVOKE ALL ON FUNCTION public.crear_punto(text, double precision, double precision, jsonb),
  public.crear_poligono(text, jsonb, jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.crear_punto(text, double precision, double precision, jsonb),
  public.crear_poligono(text, jsonb, jsonb) TO authenticated;

COMMIT;

-- Control: cuántos elementos ve la web de cada capa
SELECT 'Amojonamiento' AS capa, count(*) FROM public.v_amojonamiento
UNION ALL SELECT 'Triangulos', count(*) FROM public.v_triangulos
UNION ALL SELECT 'Padrones', count(*) FROM public.v_padrones;
