-- =====================================================================
-- PARTE 5 — Capa Relevamiento en la web   (Neon > SQL Editor)
-- Requiere las partes 1 a 4. No cambia datos existentes ni contraseñas.
-- Después de correrlo: Neon > Data API > "Refresh schema cache".
--
-- - La web puede ver la capa "Relevamiento" (solo usuarios habilitados).
-- - Los editores pueden agregar puntos de relevamiento con su Z, igual que
--   en QField: LAT, LONG y MAPS se completan con las mismas fórmulas.
-- =====================================================================
BEGIN;

-- 1. Lectura desde la web (QGIS y QField entran con neondb_owner y no se ven afectados)
GRANT SELECT ON public."Relevamiento" TO authenticated;
ALTER TABLE public."Relevamiento" ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS web_ver ON public."Relevamiento";
CREATE POLICY web_ver ON public."Relevamiento" FOR SELECT TO authenticated USING (public.rol_web() IS NOT NULL);

-- Si fid no se numera solo (pasó al importar las capas), se le pone numeración automática.
DO $$
DECLARE v_max bigint;
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns
             WHERE table_schema = 'public' AND table_name = 'Relevamiento' AND column_name = 'fid'
               AND column_default IS NULL AND is_identity = 'NO') THEN
    ALTER TABLE public."Relevamiento" ALTER COLUMN fid ADD GENERATED BY DEFAULT AS IDENTITY;
    SELECT coalesce(max(fid), 0) + 1 INTO v_max FROM public."Relevamiento";
    PERFORM setval(pg_get_serial_sequence('public."Relevamiento"', 'fid'), v_max, false);
  END IF;
END $$;

-- 2. Vista para la web, con latitud y longitud en WGS 84.
--    Se arma con las columnas que existan de verdad en la capa (si falta alguna, queda vacía).
DO $$
DECLARE
  v_geom text;
  col    text;
  v_sel  text := '';
  par    record;
BEGIN
  SELECT f_geometry_column INTO v_geom FROM geometry_columns
  WHERE f_table_schema = 'public' AND f_table_name = 'Relevamiento' LIMIT 1;
  IF v_geom IS NULL THEN RAISE EXCEPTION 'La tabla "Relevamiento" no tiene columna de geometría registrada'; END IF;

  FOR par IN SELECT * FROM (VALUES ('CÓDIGO', 'codigo'), ('DESCRIPCIÓN', 'descripcion'), ('Z', 'z'), ('MAPS', 'maps')) AS t(columna, alias) LOOP
    -- busca la columna sin importar mayúsculas ni tildes
    SELECT c.column_name INTO col FROM information_schema.columns c
    WHERE c.table_schema = 'public' AND c.table_name = 'Relevamiento'
      AND translate(upper(c.column_name), 'ÁÉÍÓÚ', 'AEIOU') = translate(upper(par.columna), 'ÁÉÍÓÚ', 'AEIOU')
    LIMIT 1;
    v_sel := v_sel || CASE WHEN col IS NULL THEN format('NULL::text AS %I, ', par.alias)
                           ELSE format('r.%I::text AS %I, ', col, par.alias) END;
  END LOOP;

  EXECUTE 'DROP VIEW IF EXISTS public.v_relevamiento';
  EXECUTE format($v$
    CREATE VIEW public.v_relevamiento WITH (security_invoker = true) AS
    SELECT r.fid AS id, %s
      ST_Y(ST_Transform(ST_Centroid(ST_Force2D(r.%I)), 4326)) AS lat,
      ST_X(ST_Transform(ST_Centroid(ST_Force2D(r.%I)), 4326)) AS lon
    FROM public."Relevamiento" r
    WHERE r.%I IS NOT NULL$v$, v_sel, v_geom, v_geom, v_geom);
END $$;
GRANT SELECT ON public.v_relevamiento TO authenticated;

-- 3. Agregar puntos: misma función de la parte 4, ahora también para Relevamiento.
--    La geometría se arma según la columna de cada capa (con Z o sin Z, punto o multipunto).
CREATE OR REPLACE FUNCTION public.crear_punto(p_capa text, p_lat double precision, p_lon double precision, p_datos jsonb)
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_tabla  text;
  v_geom   geometry;
  v_wgs    geometry;
  v_lat    double precision;
  v_lon    double precision;
  v_z      double precision;
  v_dim    integer;
  v_tipo   text;
  v_datos  jsonb := coalesce(p_datos, '{}'::jsonb);
  v_cols   text;
  v_nuevo  integer;
BEGIN
  IF coalesce(public.rol_web(), '') <> 'EDITOR' THEN
    RAISE EXCEPTION 'Solo un usuario con permiso de editor puede agregar puntos';
  END IF;
  v_tabla := CASE p_capa WHEN 'estructura' THEN 'Estructuras OICI Obra' WHEN 'obra' THEN 'Obras'
                         WHEN 'relevamiento' THEN 'Relevamiento' END;
  IF v_tabla IS NULL THEN RAISE EXCEPTION 'Capa desconocida: %', p_capa; END IF;
  IF p_lat IS NULL OR p_lon IS NULL OR p_lat NOT BETWEEN -36 AND -29 OR p_lon NOT BETWEEN -59.5 AND -52 THEN
    RAISE EXCEPTION 'Las coordenadas (%, %) quedan fuera de Uruguay. Revisá que la latitud vaya primero.', p_lat, p_lon;
  END IF;
  IF p_capa <> 'relevamiento' AND nullif(trim(v_datos->>'CÓDIGO'), '') IS NULL THEN
    RAISE EXCEPTION 'Falta el código';
  END IF;

  -- Z del relevamiento (altura que da el GPS del celular, en metros)
  BEGIN
    v_z := nullif(replace(trim(v_datos->>'Z'), ',', '.'), '')::double precision;
  EXCEPTION WHEN others THEN
    RAISE EXCEPTION 'La Z tiene que ser un número en metros (ej. 34.5)';
  END;

  -- Cómo es la geometría de la capa
  SELECT coord_dimension, upper(type) INTO v_dim, v_tipo
  FROM geometry_columns WHERE f_table_schema = 'public' AND f_table_name = v_tabla AND f_geometry_column = 'geom';

  v_geom := ST_Transform(ST_SetSRID(ST_MakePoint(p_lon, p_lat), 4326), 31981);
  IF coalesce(v_dim, 2) >= 3 OR (v_tipo LIKE '%Z' OR p_capa = 'estructura') THEN
    v_geom := ST_SetSRID(ST_MakePoint(ST_X(v_geom), ST_Y(v_geom), coalesce(v_z, 0)), 31981);
  END IF;
  IF v_tipo LIKE 'MULTI%' THEN v_geom := ST_Multi(v_geom); END IF;

  -- LAT / LONG / enlaces como en QGIS: se calculan desde la geometría guardada
  v_wgs := ST_Transform(ST_Centroid(ST_Force2D(v_geom)), 4326);
  v_lat := ST_Y(v_wgs); v_lon := ST_X(v_wgs);
  v_datos := v_datos || jsonb_build_object('LAT', v_lat, 'LONG', v_lon);
  IF p_capa = 'relevamiento' THEN
    v_datos := v_datos || jsonb_build_object(
      'MAPS', 'https://www.google.com/maps/search/?api=1&query=' || v_lat::text || ',' || v_lon::text);
    IF v_z IS NOT NULL THEN v_datos := v_datos || jsonb_build_object('Z', v_z); ELSE v_datos := v_datos - 'Z'; END IF;
  ELSE
    v_datos := v_datos || jsonb_build_object(
      'Maps', 'https://www.google.com/maps/dir/?api=1&destination=' || v_lat::text || '%2C' || v_lon::text || '&travelmode=driving',
      'WAZE', 'https://waze.com/ul?ll=' || v_lat::text || ',' || v_lon::text || '&navigate=yes',
      'Waze', 'https://waze.com/ul?ll=' || v_lat::text || ',' || v_lon::text || '&navigate=yes');
  END IF;

  -- Solo las columnas que existen en la capa (nunca fid, geom ni ETAPA: los pone la base)
  SELECT string_agg(quote_ident(k), ', ') INTO v_cols
  FROM jsonb_object_keys(v_datos) AS k
  WHERE k NOT IN ('fid', 'geom', 'ETAPA')
    AND EXISTS (SELECT 1 FROM information_schema.columns c
                WHERE c.table_schema = 'public' AND c.table_name = v_tabla AND c.column_name = k);

  EXECUTE format('INSERT INTO public.%I (%s, geom) SELECT %s, $2 FROM jsonb_populate_record(NULL::public.%I, $1) RETURNING fid',
                 v_tabla, v_cols, v_cols, v_tabla)
    USING v_datos, v_geom INTO v_nuevo;
  RETURN v_nuevo;
END $$;

REVOKE ALL ON FUNCTION public.crear_punto(text, double precision, double precision, jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.crear_punto(text, double precision, double precision, jsonb) TO authenticated;

COMMIT;
