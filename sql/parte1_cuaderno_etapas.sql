-- 3) HITOS (de una estructura o de una obra) ---------------------------
CREATE TABLE IF NOT EXISTS public.hitos (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estructura_id  integer REFERENCES public."Estructuras OICI Obra"(fid) ON DELETE CASCADE,
  obra_id        integer REFERENCES public."Obras"(fid) ON DELETE CASCADE,
  orden          integer,
  nombre         text NOT NULL,
  etapa          smallint,
  estado         text NOT NULL DEFAULT 'PENDIENTE'
                 CHECK (estado IN ('PENDIENTE','EN CURSO','HECHO','NO APLICA')),
  fecha_prevista date,
  fecha_real     date,
  recordatorio   date,
  notas          text,
  creado         timestamptz NOT NULL DEFAULT now(),
  modificado     timestamptz NOT NULL DEFAULT now(),
  CHECK (num_nonnulls(estructura_id, obra_id) = 1)
);
CREATE INDEX IF NOT EXISTS hitos_estructura_idx ON public.hitos(estructura_id);
CREATE INDEX IF NOT EXISTS hitos_obra_idx       ON public.hitos(obra_id);

-- 4) CUADERNO de obra --------------------------------------------------
CREATE TABLE IF NOT EXISTS public.cuaderno (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estructura_id  integer REFERENCES public."Estructuras OICI Obra"(fid) ON DELETE CASCADE,
  obra_id        integer REFERENCES public."Obras"(fid) ON DELETE CASCADE,
  fecha          date NOT NULL DEFAULT current_date,
  tipo           text NOT NULL DEFAULT 'NOTA'
                 CHECK (tipo IN ('NOTA','VISITA','PROBLEMA','PEDIDO','ACTA')),
  texto          text NOT NULL,
  foto           text,
  autor          text,
  creado         timestamptz NOT NULL DEFAULT now(),
  CHECK (num_nonnulls(estructura_id, obra_id) = 1)
);
CREATE INDEX IF NOT EXISTS cuaderno_estructura_idx ON public.cuaderno(estructura_id);
CREATE INDEX IF NOT EXISTS cuaderno_obra_idx       ON public.cuaderno(obra_id);

-- 5) Al crear una estructura u obra nueva: cargar sus hitos -------------
CREATE OR REPLACE FUNCTION public.cargar_hitos_plantilla() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_capa text := CASE WHEN TG_TABLE_NAME = 'Obras' THEN 'OBRAS' ELSE 'ESTRUCTURAS' END;
BEGIN
  INSERT INTO public.hitos (estructura_id, obra_id, orden, nombre, etapa, fecha_prevista)
  SELECT CASE WHEN v_capa = 'ESTRUCTURAS' THEN NEW.fid END,
         CASE WHEN v_capa = 'OBRAS'       THEN NEW.fid END,
         p.orden, p.nombre, p.etapa, NULL
  FROM public.plantilla_hitos p
  WHERE p.capa = v_capa;
  RETURN NEW;
EXCEPTION WHEN others THEN
  RAISE WARNING 'No se cargaron hitos para % %: %', v_capa, NEW.fid, SQLERRM;
  RETURN NEW;  -- la obra se guarda igual
END $$;

DROP TRIGGER IF EXISTS estructura_nueva_hitos ON public."Estructuras OICI Obra";
CREATE TRIGGER estructura_nueva_hitos AFTER INSERT ON public."Estructuras OICI Obra"
  FOR EACH ROW EXECUTE FUNCTION public.cargar_hitos_plantilla();

DROP TRIGGER IF EXISTS obra_nueva_hitos ON public."Obras";
CREATE TRIGGER obra_nueva_hitos AFTER INSERT ON public."Obras"
  FOR EACH ROW EXECUTE FUNCTION public.cargar_hitos_plantilla();

-- Etapa 1 por defecto para las estructuras nuevas
CREATE OR REPLACE FUNCTION public.etapa_inicial() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW."ETAPA" IS NULL THEN NEW."ETAPA" := 1; END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS estructura_etapa_inicial ON public."Estructuras OICI Obra";
CREATE TRIGGER estructura_etapa_inicial BEFORE INSERT ON public."Estructuras OICI Obra"
  FOR EACH ROW EXECUTE FUNCTION public.etapa_inicial();

-- 6) Al marcar un hito: actualizar ETAPA, ESTADO, FECHA FIN y RECEPCIÓN --
CREATE OR REPLACE FUNCTION public.actualizar_etapa() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_id      integer := COALESCE(NEW.estructura_id, OLD.estructura_id);
  v_etapa   smallint;
  v_fin     date;
  v_rprov   boolean;
BEGIN
  IF v_id IS NULL THEN RETURN NULL; END IF;   -- hitos de "Obras": no tocan etapas

  SELECT COALESCE(max(etapa) FILTER (WHERE estado = 'HECHO'), 1),
         max(fecha_real) FILTER (WHERE estado = 'HECHO' AND etapa = 5),
         bool_or(estado = 'HECHO' AND nombre ILIKE 'Recepción provisoria%')
    INTO v_etapa, v_fin, v_rprov
  FROM public.hitos WHERE estructura_id = v_id;

  UPDATE public."Estructuras OICI Obra" o SET
    "ETAPA"  = v_etapa,
    "ESTADO" = CASE WHEN v_etapa >= 5 THEN 'FIN'
                    WHEN v_etapa >= 3 THEN 'CONS'
                    -- se desmarcó el fin de obra (no al crear una obra ya terminada)
                    WHEN o."ESTADO" = 'FIN' AND TG_OP <> 'INSERT' THEN 'CONS'
                    ELSE o."ESTADO" END,
    "RECEPCIÓN" = CASE WHEN v_etapa >= 6 THEN 'RD'
                       WHEN v_rprov AND COALESCE(o."RECEPCIÓN",'') = '' THEN 'RP'
                       ELSE o."RECEPCIÓN" END
  WHERE o.fid = v_id;

  -- FECHA FIN: si se marcó el fin de obra y no tenía fecha, toma la del hito
  IF v_etapa >= 5 AND v_fin IS NOT NULL THEN
    UPDATE public."Estructuras OICI Obra"
       SET "FECHA FIN" = v_fin
     WHERE fid = v_id AND "FECHA FIN" IS NULL;
  END IF;
  RETURN NULL;
END $$;

DROP TRIGGER IF EXISTS hitos_actualizan_etapa ON public.hitos;
CREATE TRIGGER hitos_actualizan_etapa
  AFTER INSERT OR UPDATE OF estado, fecha_real OR DELETE ON public.hitos
  FOR EACH ROW EXECUTE FUNCTION public.actualizar_etapa();

CREATE OR REPLACE FUNCTION public.tocar_modificado() RETURNS trigger
LANGUAGE plpgsql AS $$ BEGIN NEW.modificado := now(); RETURN NEW; END $$;
DROP TRIGGER IF EXISTS hitos_modificado ON public.hitos;
CREATE TRIGGER hitos_modificado BEFORE UPDATE ON public.hitos
  FOR EACH ROW EXECUTE FUNCTION public.tocar_modificado();

-- 7) Cargar hitos a las estructuras que YA existen ----------------------
--    Se marcan como hechos según el estado actual:
--      FIN  -> hitos hasta "fin de obra" hechos (fecha real = FECHA FIN)
--      CONS -> solo "proyecto ejecutivo" hecho (revisar hormigonado/montaje a mano)
--      RD   -> además, recepción definitiva hecha
INSERT INTO public.hitos (estructura_id, orden, nombre, etapa, estado, fecha_real)
SELECT o.fid, p.orden, p.nombre, p.etapa,
  CASE
    WHEN o."RECEPCIÓN" = 'RD' AND p.etapa IS NOT NULL                 THEN 'HECHO'
    WHEN o."RECEPCIÓN" IN ('RP','PD','RD') AND p.etapa IS NULL        THEN 'HECHO'
    WHEN o."ESTADO" = 'FIN'  AND p.etapa <= 5                         THEN 'HECHO'
    WHEN o."ESTADO" = 'CONS' AND p.etapa <= 2                         THEN 'HECHO'
    ELSE 'PENDIENTE' END,
  CASE WHEN o."ESTADO" = 'FIN' AND p.etapa = 5 THEN o."FECHA FIN"::date END
FROM public."Estructuras OICI Obra" o
CROSS JOIN public.plantilla_hitos p
WHERE p.capa = 'ESTRUCTURAS'
  AND NOT EXISTS (SELECT 1 FROM public.hitos h WHERE h.estructura_id = o.fid);
-- (el disparador del punto 6 calcula ETAPA de cada una al insertar)

UPDATE public."Estructuras OICI Obra" SET "ETAPA" = 1 WHERE "ETAPA" IS NULL;

-- 8) VISTAS para la web (nombres limpios, coordenadas en grados) --------
CREATE OR REPLACE VIEW public.v_estructuras WITH (security_invoker = true) AS
SELECT
  o.fid AS id, o."CÓDIGO" AS codigo, o."ESTADO" AS estado, o."ETAPA" AS etapa,
  o."ESTRUCTURA" AS estructura, o."LICITACIÓN" AS licitacion, o."AÑO" AS anio,
  o."D.O." AS director_obra, o."RECEPCIÓN" AS recepcion,
  o."FECHA INICIO"::date AS fecha_inicio, o."FECHA FIN"::date AS fecha_fin,
  CASE WHEN o."FECHA FIN" IS NOT NULL
       THEN (o."FECHA FIN"::date + interval '2 years')::date END AS vence_recepcion,
  CASE WHEN o."FECHA FIN" IS NOT NULL AND COALESCE(o."RECEPCIÓN",'') <> 'RD'
       THEN (o."FECHA FIN"::date + interval '2 years')::date - current_date END AS dias_para_recepcion,
  o."PLANOS" AS planos, o."OBSERVACIONES" AS observaciones,
  ST_Y(ST_Transform(o.geom, 4326)) AS lat, ST_X(ST_Transform(o.geom, 4326)) AS lon,
  (SELECT count(*) FROM public.hitos h WHERE h.estructura_id = o.fid AND h.estado = 'HECHO')      AS hitos_hechos,
  (SELECT count(*) FROM public.hitos h WHERE h.estructura_id = o.fid AND h.estado <> 'NO APLICA') AS hitos_total,
  (SELECT min(COALESCE(h.recordatorio, h.fecha_prevista)) FROM public.hitos h
     WHERE h.estructura_id = o.fid AND h.estado IN ('PENDIENTE','EN CURSO'))                    AS proximo_vencimiento
FROM public."Estructuras OICI Obra" o;

CREATE OR REPLACE VIEW public.v_obras WITH (security_invoker = true) AS
SELECT
  o.fid AS id, o."CÓDIGO" AS codigo, o."Estado" AS estado, o."Sala" AS sala,
  o."Localidad" AS localidad, o."Departamento" AS departamento,
  o."Licitación" AS licitacion, o."Tarea" AS tarea, o."Descripción" AS descripcion,
  o."D.O." AS director_obra, o."Planos" AS planos,
  ST_Y(ST_Transform(o.geom, 4326)) AS lat, ST_X(ST_Transform(o.geom, 4326)) AS lon,
  (SELECT count(*) FROM public.hitos h WHERE h.obra_id = o.fid AND h.estado = 'HECHO')      AS hitos_hechos,
  (SELECT count(*) FROM public.hitos h WHERE h.obra_id = o.fid AND h.estado <> 'NO APLICA') AS hitos_total,
  (SELECT min(COALESCE(h.recordatorio, h.fecha_prevista)) FROM public.hitos h
     WHERE h.obra_id = o.fid AND h.estado IN ('PENDIENTE','EN CURSO'))                    AS proximo_vencimiento
FROM public."Obras" o;

COMMIT;

