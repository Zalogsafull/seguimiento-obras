-- =====================================================================
-- PARTE 21 — Numeración automática de fid en Obras y Estructuras   (Neon > SQL Editor > Run)
-- Arregla «null value in column "fid" of relation "Obras"» al agregar puntos desde la web.
-- No cambia datos existentes ni contraseñas. Se puede correr más de una vez.
-- =====================================================================
DO $do$
DECLARE t text; v_max bigint;
BEGIN
  FOREACH t IN ARRAY ARRAY['Obras', 'Estructuras OICI Obra', 'Relevamiento'] LOOP
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = t AND column_name = 'fid'
                 AND column_default IS NULL AND is_identity = 'NO') THEN
      EXECUTE format('ALTER TABLE public.%I ALTER COLUMN fid ADD GENERATED BY DEFAULT AS IDENTITY', t);
      EXECUTE format('SELECT coalesce(max(fid), 0) + 1 FROM public.%I', t) INTO v_max;
      PERFORM setval(pg_get_serial_sequence(format('public.%I', t), 'fid'), v_max, false);
      RAISE NOTICE 'fid numerado en %, sigue en %', t, v_max;
    END IF;
  END LOOP;
END $do$;
