-- PARTE 9 — Borrar estructuras, obras y puntos de relevamiento desde la web
-- (Neon > SQL Editor). Requiere las partes 2 y 3. No cambia contraseñas.
-- Después de correrlo: Neon > Data API > "Refresh schema cache".
--
-- - Un administrador borra directamente (la web pide confirmación).
-- - Un editor no borra: deja una solicitud, y un administrador la aprueba o la rechaza.
-- - Antes de borrar se guarda una copia completa (datos, hitos y cuaderno) en
--   solicitudes_borrado.respaldo, por si hay que recuperar algo.
-- =====================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS public.solicitudes_borrado (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo          text NOT NULL CHECK (tipo IN ('estructura', 'obra', 'relevamiento')),
  objeto_id     integer NOT NULL,
  codigo        text,
  motivo        text,
  pedido_por    text NOT NULL,
  pedido_nombre text,
  creado        timestamptz NOT NULL DEFAULT now(),
  estado        text NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'APROBADA', 'RECHAZADA', 'BORRADA')),
  resuelto_por  text,
  resuelto      timestamptz,
  respaldo      jsonb
);
-- La web no toca la tabla directamente: todo pasa por las funciones de abajo.
REVOKE ALL ON public.solicitudes_borrado FROM PUBLIC;
ALTER TABLE public.solicitudes_borrado ENABLE ROW LEVEL SECURITY;

-- Tabla y columna de código de cada tipo
CREATE OR REPLACE FUNCTION public.tabla_de_tipo(p_tipo text) RETURNS text
LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE p_tipo WHEN 'estructura' THEN 'Estructuras OICI Obra' WHEN 'obra' THEN 'Obras'
                     WHEN 'relevamiento' THEN 'Relevamiento' END
$$;

-- Borra un elemento y devuelve la copia de respaldo (uso interno, no lo llama la web)
CREATE OR REPLACE FUNCTION public.borrar_elemento(p_tipo text, p_id integer) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_tabla text := public.tabla_de_tipo(p_tipo);
  v_fila  jsonb;
  v_resp  jsonb;
BEGIN
  IF v_tabla IS NULL THEN RAISE EXCEPTION 'Capa desconocida: %', p_tipo; END IF;
  EXECUTE format('SELECT to_jsonb(t) FROM public.%I t WHERE fid = $1', v_tabla) INTO v_fila USING p_id;
  IF v_fila IS NULL THEN RAISE EXCEPTION 'Ya no existe: puede que otra persona lo haya borrado'; END IF;
  v_resp := jsonb_build_object('capa', v_tabla, 'fila', v_fila);
  IF p_tipo IN ('estructura', 'obra') THEN
    v_resp := v_resp || jsonb_build_object(
      'hitos', (SELECT coalesce(jsonb_agg(to_jsonb(h)), '[]') FROM public.hitos h
                WHERE (p_tipo = 'estructura' AND h.estructura_id = p_id) OR (p_tipo = 'obra' AND h.obra_id = p_id)),
      'cuaderno', (SELECT coalesce(jsonb_agg(to_jsonb(c)), '[]') FROM public.cuaderno c
                   WHERE (p_tipo = 'estructura' AND c.estructura_id = p_id) OR (p_tipo = 'obra' AND c.obra_id = p_id)));
  END IF;
  -- hitos y cuaderno se borran solos (ON DELETE CASCADE)
  EXECUTE format('DELETE FROM public.%I WHERE fid = $1', v_tabla) USING p_id;
  RETURN v_resp;
END $$;
REVOKE ALL ON FUNCTION public.borrar_elemento(text, integer) FROM PUBLIC;

-- Pedido de borrado desde la web: el administrador borra; un editor deja la solicitud
CREATE OR REPLACE FUNCTION public.pedir_borrado(p_tipo text, p_id integer, p_motivo text DEFAULT NULL)
RETURNS text
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_tabla  text := public.tabla_de_tipo(p_tipo);
  v_codigo text;
  v_nombre text;
  v_resp   jsonb;
BEGIN
  IF coalesce(public.rol_web(), '') <> 'EDITOR' THEN
    RAISE EXCEPTION 'Solo un usuario con permiso de editor puede pedir que se borre algo';
  END IF;
  IF v_tabla IS NULL THEN RAISE EXCEPTION 'Capa desconocida: %', p_tipo; END IF;
  EXECUTE format('SELECT coalesce(to_jsonb(t)->>''CÓDIGO'', '''') FROM public.%I t WHERE fid = $1', v_tabla) INTO v_codigo USING p_id;
  IF v_codigo IS NULL THEN RAISE EXCEPTION 'Ya no existe: puede que otra persona lo haya borrado'; END IF;
  v_codigo := nullif(v_codigo, '');
  SELECT nombre INTO v_nombre FROM public.usuarios_web WHERE user_id = auth.user_id();

  IF public.es_admin() THEN
    v_resp := public.borrar_elemento(p_tipo, p_id);
    INSERT INTO public.solicitudes_borrado (tipo, objeto_id, codigo, motivo, pedido_por, pedido_nombre,
                                            estado, resuelto_por, resuelto, respaldo)
    VALUES (p_tipo, p_id, v_codigo, p_motivo, auth.user_id(), v_nombre, 'BORRADA', auth.user_id(), now(), v_resp);
    RETURN 'BORRADO';
  END IF;

  IF EXISTS (SELECT 1 FROM public.solicitudes_borrado
             WHERE tipo = p_tipo AND objeto_id = p_id AND estado = 'PENDIENTE') THEN
    RETURN 'YA_PEDIDO';
  END IF;
  INSERT INTO public.solicitudes_borrado (tipo, objeto_id, codigo, motivo, pedido_por, pedido_nombre)
  VALUES (p_tipo, p_id, v_codigo, nullif(trim(p_motivo), ''), auth.user_id(), v_nombre);
  RETURN 'PEDIDO';
END $$;

-- Solicitudes pendientes: el administrador ve todas; un editor, las suyas
CREATE OR REPLACE FUNCTION public.solicitudes_pendientes() RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT coalesce(jsonb_agg(jsonb_build_object(
           'id', s.id, 'tipo', s.tipo, 'objeto_id', s.objeto_id, 'codigo', s.codigo, 'motivo', s.motivo,
           'pedido_nombre', s.pedido_nombre, 'creado', s.creado, 'mia', s.pedido_por = auth.user_id())
         ORDER BY s.creado), '[]'::jsonb)
  FROM public.solicitudes_borrado s
  WHERE s.estado = 'PENDIENTE' AND public.rol_web() IS NOT NULL
    AND (public.es_admin() OR s.pedido_por = auth.user_id())
$$;

-- El administrador aprueba (se borra) o rechaza
CREATE OR REPLACE FUNCTION public.resolver_borrado(p_solicitud integer, p_aprobar boolean)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  s public.solicitudes_borrado;
  v_resp jsonb;
BEGIN
  IF NOT public.es_admin() THEN RAISE EXCEPTION 'Solo un administrador puede aprobar o rechazar'; END IF;
  SELECT * INTO s FROM public.solicitudes_borrado WHERE id = p_solicitud AND estado = 'PENDIENTE' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Esa solicitud ya fue resuelta'; END IF;
  IF p_aprobar THEN
    v_resp := public.borrar_elemento(s.tipo, s.objeto_id);
  END IF;
  UPDATE public.solicitudes_borrado
     SET estado = CASE WHEN p_aprobar THEN 'APROBADA' ELSE 'RECHAZADA' END,
         resuelto_por = auth.user_id(), resuelto = now(), respaldo = v_resp
   WHERE id = p_solicitud;
END $$;

REVOKE ALL ON FUNCTION public.pedir_borrado(text, integer, text), public.solicitudes_pendientes(),
  public.resolver_borrado(integer, boolean), public.tabla_de_tipo(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.pedir_borrado(text, integer, text), public.solicitudes_pendientes(),
  public.resolver_borrado(integer, boolean) TO authenticated;

COMMIT;
