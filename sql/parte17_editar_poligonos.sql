CREATE TABLE IF NOT EXISTS public.solicitudes_forma (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo          text NOT NULL CHECK (tipo IN ('triangulo', 'padron')),
  objeto_id     integer NOT NULL,
  codigo        text,
  vertices      jsonb NOT NULL,
  datos         jsonb,
  pedido_por    text NOT NULL,
  pedido_nombre text,
  creado        timestamptz NOT NULL DEFAULT now(),
  estado        text NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'APROBADA', 'RECHAZADA', 'APLICADA')),
  resuelto_por  text,
  resuelto      timestamptz,
  respaldo      jsonb
);
REVOKE ALL ON public.solicitudes_forma FROM PUBLIC;
ALTER TABLE public.solicitudes_forma ENABLE ROW LEVEL SECURITY;

-- Arma el polígono (SIRGAS UTM 21 S) a partir de vértices WGS 84 [[lon, lat], ...] (uso interno)
CREATE OR REPLACE FUNCTION public.armar_poligono(p_tabla text, p_vertices jsonb) RETURNS geometry
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $fn$
DECLARE
  v_pts  geometry[];
  v_geom geometry;
  v_dim  integer;
  v_tipo text;
  v_p    jsonb;
  v_lon  double precision;
  v_lat  double precision;
BEGIN
  IF jsonb_typeof(p_vertices) <> 'array' OR jsonb_array_length(p_vertices) < 3 THEN
    RAISE EXCEPTION 'Un polígono necesita al menos 3 vértices';
  END IF;
  FOR v_p IN SELECT * FROM jsonb_array_elements(p_vertices) LOOP
    v_lon := (v_p->>0)::double precision;
    v_lat := (v_p->>1)::double precision;
    IF v_lat IS NULL OR v_lon IS NULL OR v_lat NOT BETWEEN -36 AND -29 OR v_lon NOT BETWEEN -59.5 AND -52 THEN
      RAISE EXCEPTION 'El vértice (%, %) queda fuera de Uruguay', v_lat, v_lon;
    END IF;
    v_pts := v_pts || ST_Transform(ST_SetSRID(ST_MakePoint(v_lon, v_lat), 4326), 31981);
  END LOOP;
  IF NOT ST_Equals(v_pts[1], v_pts[array_length(v_pts, 1)]) THEN
    v_pts := v_pts || v_pts[1];
  END IF;
  v_geom := ST_MakePolygon(ST_MakeLine(v_pts));
  IF NOT ST_IsValid(v_geom) THEN
    v_geom := ST_CollectionExtract(ST_MakeValid(v_geom), 3);
    IF ST_NumGeometries(v_geom) = 1 THEN
      v_geom := ST_GeometryN(v_geom, 1);
    END IF;
  END IF;
  IF ST_IsEmpty(v_geom) OR ST_Area(v_geom) < 1 THEN
    RAISE EXCEPTION 'Los vértices no forman un polígono (quedan en línea o repetidos)';
  END IF;
  SELECT coord_dimension, upper(type) INTO v_dim, v_tipo
  FROM geometry_columns WHERE f_table_schema = 'public' AND f_table_name = p_tabla AND f_geometry_column = 'geom';
  IF v_tipo LIKE 'MULTI%' THEN
    v_geom := ST_Multi(v_geom);
  ELSIF GeometryType(v_geom) = 'MULTIPOLYGON' THEN
    RAISE EXCEPTION 'Los vértices se cruzan y forman más de un polígono: revisá el orden';
  END IF;
  IF coalesce(v_dim, 2) >= 3 THEN
    v_geom := ST_Force3D(v_geom);
  END IF;
  RETURN ST_SetSRID(v_geom, 31981);
END $fn$;
REVOKE ALL ON FUNCTION public.armar_poligono(text, jsonb) FROM PUBLIC;

-- Aplica la forma nueva (y el código o número de padrón) y devuelve el respaldo (uso interno)
CREATE OR REPLACE FUNCTION public.aplicar_forma(p_tipo text, p_id integer, p_vertices jsonb, p_datos jsonb) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $fn$
DECLARE
  v_tabla text;
  v_col   text;
  v_fila  jsonb;
  v_geom  geometry;
  v_valor text;
BEGIN
  v_tabla := CASE p_tipo WHEN 'triangulo' THEN 'Triangulos' WHEN 'padron' THEN 'Padrones' END;
  IF v_tabla IS NULL THEN
    RAISE EXCEPTION 'Capa desconocida: %', p_tipo;
  END IF;
  EXECUTE format('SELECT to_jsonb(t) - ''geom'' || jsonb_build_object(''wkt'', ST_AsText(t.geom)) FROM public.%I t WHERE fid = $1', v_tabla)
    INTO v_fila USING p_id;
  IF v_fila IS NULL THEN
    RAISE EXCEPTION 'Ya no existe: puede que otra persona lo haya borrado';
  END IF;
  v_geom := public.armar_poligono(v_tabla, p_vertices);
  EXECUTE format('UPDATE public.%I SET geom = $1 WHERE fid = $2', v_tabla) USING v_geom, p_id;
  v_col := CASE p_tipo WHEN 'triangulo' THEN 'CÓDIGO' ELSE 'PADRON' END;
  IF coalesce(p_datos, '{}'::jsonb) ? v_col AND EXISTS (SELECT 1 FROM information_schema.columns c
       WHERE c.table_schema = 'public' AND c.table_name = v_tabla AND c.column_name = v_col) THEN
    v_valor := nullif(trim(p_datos->>v_col), '');
    IF p_tipo = 'padron' AND v_valor IS NOT NULL AND v_valor !~ '^\d{1,9}$' THEN
      RAISE EXCEPTION 'El número de padrón tiene que ser un número entero';
    END IF;
    IF p_tipo = 'padron' THEN
      EXECUTE format('UPDATE public.%I SET %I = $1::integer WHERE fid = $2', v_tabla, v_col) USING v_valor, p_id;
    ELSE
      EXECUTE format('UPDATE public.%I SET %I = $1 WHERE fid = $2', v_tabla, v_col) USING v_valor, p_id;
    END IF;
  END IF;
  RETURN jsonb_build_object('capa', v_tabla, 'antes', v_fila);
END $fn$;
REVOKE ALL ON FUNCTION public.aplicar_forma(text, integer, jsonb, jsonb) FROM PUBLIC;

-- Desde la web: el administrador aplica; un editor deja el cambio pendiente
CREATE OR REPLACE FUNCTION public.editar_poligono(p_tipo text, p_id integer, p_vertices jsonb, p_datos jsonb)
RETURNS text
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $fn$
DECLARE
  v_tabla  text;
  v_fila   jsonb;
  v_codigo text;
  v_nombre text;
  v_resp   jsonb;
BEGIN
  IF coalesce(public.rol_web(), '') <> 'EDITOR' THEN
    RAISE EXCEPTION 'Solo un usuario con permiso de editor puede cambiar polígonos';
  END IF;
  v_tabla := CASE p_tipo WHEN 'triangulo' THEN 'Triangulos' WHEN 'padron' THEN 'Padrones' END;
  IF v_tabla IS NULL THEN
    RAISE EXCEPTION 'Capa desconocida: %', p_tipo;
  END IF;
  EXECUTE format('SELECT to_jsonb(t) - ''geom'' FROM public.%I t WHERE fid = $1', v_tabla) INTO v_fila USING p_id;
  IF v_fila IS NULL THEN
    RAISE EXCEPTION 'Ya no existe: puede que otra persona lo haya borrado';
  END IF;
  PERFORM public.armar_poligono(v_tabla, p_vertices);
  v_codigo := nullif(coalesce(v_fila->>'CÓDIGO',
                              CASE WHEN v_fila ? 'PADRON' THEN 'Padrón ' || coalesce(v_fila->>'PADRON', 'sin número') END, ''), '');
  SELECT nombre INTO v_nombre FROM public.usuarios_web WHERE user_id = auth.user_id();

  IF public.es_admin() THEN
    v_resp := public.aplicar_forma(p_tipo, p_id, p_vertices, p_datos);
    INSERT INTO public.solicitudes_forma (tipo, objeto_id, codigo, vertices, datos, pedido_por, pedido_nombre,
                                          estado, resuelto_por, resuelto, respaldo)
    VALUES (p_tipo, p_id, v_codigo, p_vertices, p_datos, auth.user_id(), v_nombre, 'APLICADA', auth.user_id(), now(), v_resp);
    RETURN 'APLICADO';
  END IF;

  UPDATE public.solicitudes_forma SET vertices = p_vertices, datos = p_datos, creado = now()
  WHERE tipo = p_tipo AND objeto_id = p_id AND estado = 'PENDIENTE' AND pedido_por = auth.user_id();
  IF NOT FOUND THEN
    INSERT INTO public.solicitudes_forma (tipo, objeto_id, codigo, vertices, datos, pedido_por, pedido_nombre)
    VALUES (p_tipo, p_id, v_codigo, p_vertices, p_datos, auth.user_id(), v_nombre);
  END IF;
  RETURN 'PEDIDO';
END $fn$;

-- Cambios pendientes: el administrador ve todos; un editor, los suyos
CREATE OR REPLACE FUNCTION public.cambios_forma_pendientes() RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $fn$
  SELECT coalesce(jsonb_agg(jsonb_build_object(
           'id', s.id, 'tipo', s.tipo, 'objeto_id', s.objeto_id, 'codigo', s.codigo, 'vertices', s.vertices,
           'datos', s.datos, 'pedido_nombre', s.pedido_nombre, 'creado', s.creado, 'mia', s.pedido_por = auth.user_id())
         ORDER BY s.creado), '[]'::jsonb)
  FROM public.solicitudes_forma s
  WHERE s.estado = 'PENDIENTE' AND public.rol_web() IS NOT NULL
    AND (public.es_admin() OR s.pedido_por = auth.user_id())
$fn$;

-- El administrador aprueba (se aplica) o rechaza
CREATE OR REPLACE FUNCTION public.resolver_forma(p_solicitud integer, p_aprobar boolean)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $fn$
DECLARE
  s public.solicitudes_forma;
  v_resp jsonb;
BEGIN
  IF NOT public.es_admin() THEN
    RAISE EXCEPTION 'Solo un administrador puede aprobar o rechazar';
  END IF;
  SELECT * INTO s FROM public.solicitudes_forma WHERE id = p_solicitud AND estado = 'PENDIENTE' FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Ese cambio ya fue resuelto';
  END IF;
  IF p_aprobar THEN
    v_resp := public.aplicar_forma(s.tipo, s.objeto_id, s.vertices, s.datos);
  END IF;
  UPDATE public.solicitudes_forma
     SET estado = CASE WHEN p_aprobar THEN 'APROBADA' ELSE 'RECHAZADA' END,
         resuelto_por = auth.user_id(), resuelto = now(), respaldo = v_resp
   WHERE id = p_solicitud;
END $fn$;

REVOKE ALL ON FUNCTION public.editar_poligono(text, integer, jsonb, jsonb), public.cambios_forma_pendientes(),
  public.resolver_forma(integer, boolean) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.editar_poligono(text, integer, jsonb, jsonb), public.cambios_forma_pendientes(),
  public.resolver_forma(integer, boolean) TO authenticated;

COMMIT;

